    fn reverse_lookup_lists_short_names_first() {
        let a = abbreviations_of("α");
        assert_eq!(a.first(), Some(&"a"));
        assert!(a.contains(&"alpha"));
        assert!(abbreviations_of("→").contains(&"to"));
        assert!(abbreviations_of("⟨⟩").contains(&"<>"));
    }

    #[test]
    fn search_finds_by_abbreviation_prefix_and_symbol() {
        let hits = search("to", 10);
        assert_eq!(hits[0].text, "→", "{hits:?}");
        assert_eq!(hits[0].abbrev, "to");
        assert!(hits[0].aliases.contains(&"r"), "{:?}", hits[0].aliases);
        // the leader may be included
        assert_eq!(search("\\forall", 3)[0].text, "∀");
        // a prefix lists the longer names too
        let le: Vec<String> = search("le", 6).into_iter().map(|h| h.text).collect();
        assert_eq!(le[0], "≤", "{le:?}");
        // the symbol itself
        assert_eq!(search("→", 1)[0].text, "→");
        // a fuzzy subsequence
        assert!(search("fral", 5).iter().any(|h| h.text == "∀"));
        assert!(search("zzzzqqq", 5).is_empty());
    }

    #[test]
    fn search_lists_each_text_once() {
        let hits = search("alpha", 20);
        assert_eq!(hits.iter().filter(|h| h.text == "α").count(), 1);
        let texts: Vec<&str> = hits.iter().map(|h| h.text.as_str()).collect();
        let mut dedup = texts.clone();
        dedup.sort();
        dedup.dedup();
        assert_eq!(dedup.len(), texts.len());
        assert_eq!(search("", 5).len(), 5);
    }

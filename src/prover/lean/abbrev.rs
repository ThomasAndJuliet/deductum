//! Lean's Unicode input abbreviations: typing `\to` gives `→`, `\a` gives `α`,
//! `\<` gives `⟨`. Lean source is Unicode as written (design C17d), so the `\`
//! completion of the Lean profile inserts the character itself, as the VS Code
//! extension does; no escape stays in the file.
//!
//! The table is the official one of the vscode-lean4 repository
//! (`lean4-unicode-input/src/abbreviations.json`, 1865 entries), embedded as a
//! static sorted by abbreviation so that an exact lookup is a binary search.
//! It is not a build step. To refresh it, download the JSON and run
//!
//! ```python
//! import json, sys
//! d = json.load(open(sys.argv[1]))
//! esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
//! print("pub static TABLE: &[(&str, &str)] = &[")
//! for k in sorted(d, key=lambda s: s.encode()):
//!     print(f'    ("{esc(k)}", "{esc(d[k])}"),')
//! print("];")
//! ```
//!
//! then paste the output over `TABLE` below. A replacement may hold `$CURSOR`,
//! where the caret goes after the insert (`\<` gives `⟨$CURSOR⟩`, so the caret
//! lands between the brackets). [`expand`] takes that apart.
//!
//! Search works as `symbols::Table::search` does for Isabelle (prefix, then
//! word start, then subsequence) and returns the best abbreviation per
//! character, so the `\` menu lists each symbol once. All offsets are in code
//! points, as everywhere in the app.

/// The character that starts an abbreviation
pub const LEADER: char = '\\';

/// What an abbreviation inserts: the text, and where the caret goes in it
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Expansion {
    pub text: String,
    /// Code points from the start of `text` to the caret
    pub cursor: usize,
}

/// A symbol found by a `\` query
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Hit {
    /// What to insert (without `$CURSOR`)
    pub text: String,
    /// Code points from the start of `text` to the caret
    pub cursor: usize,
    /// The abbreviation that matched best, without the `\`
    pub abbrev: &'static str,
    /// The other abbreviations of the same text, shortest first
    pub aliases: Vec<&'static str>,
}

/// The raw replacement of an exact abbreviation (`$CURSOR` still in it)
pub fn lookup(abbrev: &str) -> Option<&'static str> {
    TABLE.binary_search_by(|(k, _)| k.as_bytes().cmp(abbrev.as_bytes())).ok().map(|i| TABLE[i].1)
}

/// What an exact abbreviation inserts, with the caret position taken out of it
pub fn expand(abbrev: &str) -> Option<Expansion> {
    lookup(abbrev).map(expansion)
}

fn expansion(raw: &str) -> Expansion {
    match raw.find("$CURSOR") {
        Some(at) => {
            let cursor = raw[..at].chars().count();
            Expansion { text: format!("{}{}", &raw[..at], &raw[at + "$CURSOR".len()..]), cursor }
        }
        None => Expansion { text: raw.to_string(), cursor: raw.chars().count() },
    }
}

/// The abbreviations that insert `text` (a character, or a bracket pair with `$CURSOR`
/// removed), shortest first: what to tell the user when they hover a symbol
pub fn abbreviations_of(text: &str) -> Vec<&'static str> {
    let mut out: Vec<&'static str> = TABLE.iter().filter(|(_, v)| *v == text || v.replacen("$CURSOR", "", 1) == text).map(|(k, _)| *k).collect();
    out.sort_by(|a, b| a.chars().count().cmp(&b.chars().count()).then(a.cmp(b)));
    out
}

/// How well `query` matches `name`: exact, prefix, inside, then a subsequence
/// (the same scale as `symbols::fuzzy`, so scores can be compared)
pub fn fuzzy(query: &str, name: &str) -> Option<i32> {
    if query.is_empty() {
        return Some(0);
    }
    let q = query.to_lowercase();
    let n = name.to_lowercase();
    if n == q {
        return Some(10_000);
    }
    if name.starts_with(query) {
        return Some(5000 - name.len() as i32);
    }
    if n.starts_with(&q) {
        return Some(4500 - name.len() as i32);
    }
    if let Some(i) = n.find(&q) {
        return Some(3000 - i as i32 * 10 - name.len() as i32);
    }
    let mut gaps = 0;
    let mut chars = n.chars();
    let mut last = 0;
    for (k, qc) in q.chars().enumerate() {
        let mut pos = last;
        loop {
            match chars.next() {
                Some(c) if c == qc => break,
                Some(_) => pos += 1,
                None => return None,
            }
        }
        if k > 0 {
            gaps += pos - last;
        }
        last = pos + 1;
    }
    Some(1000 - gaps as i32 * 20 - name.len() as i32)
}

/// Symbols matching what follows a `\`, best first, each text once. A query that is the
/// symbol itself (`→`) finds it too. An empty query lists the shortest abbreviations
pub fn search(query: &str, limit: usize) -> Vec<Hit> {
    let query = query.strip_prefix(LEADER).unwrap_or(query);
    let mut best: Vec<(i32, usize)> = Vec::new();
    let mut by_text: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
    for (i, (abbrev, raw)) in TABLE.iter().enumerate() {
        let clean = raw.replacen("$CURSOR", "", 1);
        let score = if !query.is_empty() && clean == query {
            Some(9000)
        } else {
            fuzzy(query, abbrev)
        };
        let Some(score) = score else { continue };
        // (prefer the short abbreviations a user would type)
        match by_text.get(&clean) {
            Some(&k) if best[k].0 >= score => {}
            Some(&k) => best[k] = (score, i),
            None => {
                by_text.insert(clean, best.len());
                best.push((score, i));
            }
        }
    }
    best.sort_by(|a, b| b.0.cmp(&a.0).then(TABLE[a.1].0.len().cmp(&TABLE[b.1].0.len())).then(TABLE[a.1].0.cmp(TABLE[b.1].0)));
    best.into_iter()
        .take(limit)
        .map(|(_, i)| {
            let (abbrev, raw) = TABLE[i];
            let e = expansion(raw);
            let aliases = abbreviations_of(&e.text).into_iter().filter(|a| *a != abbrev).collect();
            Hit { text: e.text, cursor: e.cursor, abbrev, aliases }
        })
        .collect()
}

